/*  The island playground: a pannable / zoomable sea that boards are dragged around on.
 *
 *  Boards snap together when two sides line up in a way the board's shape actually
 *  supports. Which pairings those are is not decided here — it is measured off the traced
 *  outline by tools/island-geometry/build.mjs and shipped as BOARD.contacts, so a coast
 *  side simply never appears in the table and can never stick to anything.
 *
 *  A snapped pair becomes a bond; bonded boards form an island that drags and rotates as
 *  one piece until it is detached again.
 */
// The geometry is regenerated by tools/island-geometry/build.mjs, and browsers cache ES
// modules hard — a stale copy silently shows the previous board shape. IslandPlayground
// imports this file with a ?v= stamp; carry that query across so the geometry is refetched
// with it instead of coming back out of the module cache.
const { BOARD, LAYOUTS } = await import('./island-geometry.js' + new URL(import.meta.url).search);

const SVG_NS = 'http://www.w3.org/2000/svg';
const RAD = Math.PI / 180, DEG = 180 / Math.PI;

/** Every land-edge contact sits within ~4.1° of a 60° step, so 60° rotation buttons can
 *  reach all of them and a small angular tolerance is enough to recognise the intent. */
const SNAP_ANGLE = 15;      // degrees
const SNAP_DIST = 34;       // board units (~0.4 of a short edge)
const ROTATE_STEP = 60;     // degrees per rotate press

// ── small vector / transform helpers ────────────────────────────────────────
// A placement is stored as { rot (deg), x, y }: the board's local centre lands on
// (x, y) after rotating about that centre. Internally we compose the equivalent
// affine form p ↦ R(th)·p + t, which is what the maths below needs.
const rot2 = (p, th) => [p[0] * Math.cos(th) - p[1] * Math.sin(th),
                         p[0] * Math.sin(th) + p[1] * Math.cos(th)];
const tfOf = b => {
  const th = b.rot * RAD, r = rot2(BOARD.center, th);
  return { th, tx: b.x - r[0], ty: b.y - r[1] };
};
const placeOf = T => {
  const r = rot2(BOARD.center, T.th);
  return { rot: T.th * DEG, x: T.tx + r[0], y: T.ty + r[1] };
};
const apply = (T, p) => { const r = rot2(p, T.th); return [r[0] + T.tx, r[1] + T.ty]; };
/** A ∘ B — apply B first, then A. */
const compose = (A, B) => {
  const r = rot2([B.tx, B.ty], A.th);
  return { th: A.th + B.th, tx: r[0] + A.tx, ty: r[1] + A.ty };
};
const invert = A => {
  const r = rot2([-A.tx, -A.ty], -A.th);
  return { th: -A.th, tx: r[0], ty: r[1] };
};
const normDeg = a => { a %= 360; if (a > 180) a -= 360; if (a < -180) a += 360; return a; };

const edgeLen = k => BOARD.edges[k].len;
const corner = k => BOARD.corners[k % 4];
/** World endpoints of edge k of a placed board. */
const edgeOf = (b, k) => { const T = tfOf(b); return [apply(T, corner(k)), apply(T, corner(k + 1))]; };

/** Slides at which guest side `ge` sits flush on host side `he`, from the measured table.
 *  Sides the board's shape can't join are simply absent, so nothing else has to know
 *  which side is coast. */
const CONTACTS = new Map();
for (const c of BOARD.contacts) {
  const key = c.he * 4 + c.ge;
  if (!CONTACTS.has(key)) CONTACTS.set(key, []);
  CONTACTS.get(key).push(c.s);
}
const flushSlides = (hostEdge, guestEdge) => CONTACTS.get(hostEdge * 4 + guestEdge) ?? [];
/** Sides that can join at all — the only ones worth testing while dragging. */
const JOINABLE = [...new Set(BOARD.contacts.flatMap(c => [c.he, c.ge]))];

/** The placement a guest board needs so its edge `ge` lies flush on the host segment
 *  P→Q at slide `s`. The guest edge is laid reversed — that is what makes the two
 *  boards sit on opposite sides of a shared boundary. */
function contactTf(P, Q, ge, s) {
  const L = Math.hypot(Q[0] - P[0], Q[1] - P[1]);
  const ux = (Q[0] - P[0]) / L, uy = (Q[1] - P[1]) / L;
  const start = [P[0] + ux * (L - s), P[1] + uy * (L - s)];
  const a = corner(ge), b = corner(ge + 1);
  const th = Math.atan2(-uy, -ux) - Math.atan2(b[1] - a[1], b[0] - a[0]);
  const r = rot2(a, th);
  return { th, tx: start[0] - r[0], ty: start[1] - r[1] };
}

// ── overlap test (shrunken outline, so a flush seam never reads as an overlap) ──
const HULL = BOARD.outlinePoints.filter((_, i) => i % 6 === 0);
function hullOf(b) {
  const T = tfOf(b);
  return HULL.map(p => { const q = apply(T, p);
    return [b.x + (q[0] - b.x) * 0.9, b.y + (q[1] - b.y) * 0.9]; });
}
function polyContains(poly, p) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++)
    if ((poly[i][1] > p[1]) !== (poly[j][1] > p[1]) &&
        p[0] < (poly[j][0] - poly[i][0]) * (p[1] - poly[i][1]) / (poly[j][1] - poly[i][1]) + poly[i][0])
      inside = !inside;
  return inside;
}
function boardsOverlap(a, b) {
  if (Math.hypot(a.x - b.x, a.y - b.y) > 140) return false;
  const pa = hullOf(a), pb = hullOf(b);
  return pa.some(p => polyContains(pb, p)) || pb.some(p => polyContains(pa, p));
}

// ── the playground ──────────────────────────────────────────────────────────
/**
 * @param {HTMLElement} host
 * @param {{ onChange?: (json: string, matchedLayoutId: string|null, matchesSeed: boolean) => void,
 *           onSelect?: (index: number, islandSize: number) => void,
 *           onActivate?: (index: number) => void }} options
 */
export function create(host, options = {}) {
  const state = {
    boards: [],          // { rot, x, y } + the presentation setBoards was given (key, letter, …)
    bonds: [],           // { a, ae, b, be, s }
    selected: -1,
    view: { cx: 0, cy: 0, scale: 1.6 },   // screen px per board unit
    /** canonical form of the arrangement that was seeded — see arrangementOf */
    seed: null,
    /** the layout id that seeded it, when one did; breaks ties in matchLayout */
    seedId: null,
    /** Layout ids a hand-built island may be recognised as, supplied by the host because
     *  which layouts are allowed is a game rule (thematic maps, board count) and not
     *  something this file should decide. */
    candidates: [],
    /** Look, don't touch: the island is fixed (thematic maps are one published island, not
     *  a set of pieces to arrange). Panning and zooming stay available — those change the
     *  view, not the arrangement. */
    locked: false,
    /** Draw the island reflected left-to-right. The boards are physical pieces printed on
     *  both sides, and the thematic side is the reverse of the one this geometry was traced
     *  from — turning a piece over mirrors it, so the whole island is seen mirrored.
     *
     *  Reflection is applied at render only. Placements, bonds and the snapping maths stay in
     *  the traced frame, so nothing about how boards fit together has to know about this. */
    mirrored: false,
  };
  let ro = null, raf = 0, notifyTimer = 0, pendingFit = false;

  // ── DOM ───────────────────────────────────────────────────────────────────
  host.classList.add('island-pg');
  host.innerHTML = `
    <svg class="island-pg__sea" aria-label="Island layout">
      <defs>
        <!-- Sun on open water: light in the middle, and #1e5670 by the time it reaches any
             edge, which is the colour the surrounding scene has settled to. r is what makes
             that true — the nearest edge is 0.45 of the box from (50%, 45%), so r must not
             exceed it, or the perimeter stops short of the deep colour and the playground
             reads as a lighter panel pasted onto the sea.
             The rim is deep-600 from Styles/site.css; the two inner stops are eased down off
             deep-300 / deep-400 to keep the ramp even now that it ends one step darker. The
             scene used to end at deep-500, which was the brightest water anywhere in the app
             and left the one page built around an island looking louder than the island on the
             landing page — the same sea has to be the same sea. -->
        <radialGradient id="ipgDeep" cx="50%" cy="45%" r="45%">
          <stop offset="0%" stop-color="#6cb6de"/><stop offset="55%" stop-color="#3d8cbe"/>
          <stop offset="100%" stop-color="#1e5670"/>
        </radialGradient>
        <pattern id="ipgSwell" width="46" height="46" patternUnits="userSpaceOnUse">
          <path d="M0 34 q11.5 -9 23 0 t23 0" fill="none" stroke="#ffffff" stroke-opacity=".13" stroke-width="1.6"/>
        </pattern>
        <filter id="ipgLift" x="-30%" y="-30%" width="160%" height="160%">
          <feDropShadow dx="0" dy="2.2" stdDeviation="2.4" flood-color="#0b3550" flood-opacity=".38"/>
        </filter>
        <!-- board-local, so one clip keeps every board's coast band inside its own land -->
        <clipPath id="ipgLandClip" clipPathUnits="userSpaceOnUse">
          <path d="${BOARD.outline}"/>
        </clipPath>
      </defs>
      <rect class="island-pg__fill" x="0" y="0" width="100%" height="100%" fill="url(#ipgDeep)"/>
      <g class="island-pg__world">
        <rect class="island-pg__swell" fill="url(#ipgSwell)"/>
        <!-- one shadow for the whole scene: shadowing each board separately would draw a
             dark ridge along every seam and break the illusion of a single landmass -->
        <g class="island-pg__boards" filter="url(#ipgLift)"></g>
        <!-- above the boards: selection and error trace a board's whole boundary, seams
             included. Left on the board itself they are painted over wherever a neighbour
             drawn later shares that edge, so a joined board lights up only along its coast -->
        <g class="island-pg__outlines"></g>
        <!-- above those: a seam hint traces the boundary two boards are about to
             share, so it would be hidden underneath them -->
        <g class="island-pg__hint"></g>
      </g>
    </svg>
    <div class="island-pg__labels"></div>`;

  const svg = host.querySelector('svg');
  const world = host.querySelector('.island-pg__world');
  const swell = host.querySelector('.island-pg__swell');
  const layer = host.querySelector('.island-pg__boards');
  const outlines = host.querySelector('.island-pg__outlines');
  const hintLayer = host.querySelector('.island-pg__hint');
  const labels = host.querySelector('.island-pg__labels');

  // ── grouping: bonds define islands ────────────────────────────────────────
  function groups() {
    const parent = state.boards.map((_, i) => i);
    const find = i => parent[i] === i ? i : (parent[i] = find(parent[i]));
    for (const bd of state.bonds) if (bd.a < parent.length && bd.b < parent.length) parent[find(bd.a)] = find(bd.b);
    return state.boards.map((_, i) => find(i));
  }
  const groupOf = i => { const g = groups(); return state.boards.map((_, k) => k).filter(k => g[k] === g[i]); };
  const edgeIsBonded = (i, e) => state.bonds.some(b => (b.a === i && b.ae === e) || (b.b === i && b.be === e));

  // ── rendering ─────────────────────────────────────────────────────────────
  /** Horizontal sign of the world→screen mapping: -1 when the island is seen mirrored. Every
   *  conversion between world and screen goes through it, so pan, pinch-zoom-to-cursor and the
   *  label overlay all follow the reflection without knowing why. */
  const mx = () => state.mirrored ? -1 : 1;

  function project(p) {
    const { cx, cy, scale } = state.view;
    return [(p[0] - cx) * scale * mx() + svg.clientWidth / 2, (p[1] - cy) * scale + svg.clientHeight / 2];
  }
  function unproject(sx, sy) {
    const { cx, cy, scale } = state.view;
    return [(sx - svg.clientWidth / 2) / (scale * mx()) + cx, (sy - svg.clientHeight / 2) / scale + cy];
  }

  function buildBoard(i) {
    const g = document.createElementNS(SVG_NS, 'g');
    g.setAttribute('class', 'island-pg__board');
    g.dataset.index = i;
    g.innerHTML =
      `<path class="ipg-land" d="${BOARD.outline}"/>` +
      `<g clip-path="url(#ipgLandClip)">` +
        // Stroked, not filled: the width comes from the geometry, the clip trims the half
        // that falls outside the land. See the generator's note on the coast.
        BOARD.coast.map(d =>
          `<path class="ipg-coast" d="${d}" fill="none" stroke-width="${BOARD.coastWidth}"/>`).join('') +
      `</g>`;
    return g;
  }

  function render() {
    raf = 0;
    const w = svg.clientWidth, h = svg.clientHeight, s = state.view.scale;
    // the world group carries pan + zoom; boards keep their own local transform
    world.setAttribute('transform',
      `translate(${w / 2} ${h / 2}) scale(${s * mx()} ${s}) translate(${-state.view.cx} ${-state.view.cy})`);
    const half = [w / (2 * s), h / (2 * s)];
    swell.setAttribute('x', state.view.cx - half[0]); swell.setAttribute('y', state.view.cy - half[1]);
    swell.setAttribute('width', half[0] * 2); swell.setAttribute('height', half[1] * 2);

    while (layer.childElementCount > state.boards.length) layer.lastElementChild.remove();
    while (layer.childElementCount < state.boards.length) layer.appendChild(buildBoard(layer.childElementCount));

    const gs = groups();
    state.boards.forEach((b, i) => {
      const node = layer.children[i];
      node.dataset.index = i;
      const r = rot2(BOARD.center, b.rot * RAD);
      node.setAttribute('transform', `translate(${b.x - r[0]} ${b.y - r[1]}) rotate(${b.rot})`);
      const sameIsland = state.selected >= 0 && gs[i] === gs[state.selected];
      node.classList.toggle('is-island', sameIsland && i !== state.selected);
      node.classList.toggle('is-blocked', !!(drag?.blocked && drag.group.includes(i)));
      const land = node.querySelector('.ipg-land');
      land.setAttribute('fill', b.color || '#e8dcb8');
    });
    renderOutlines();
    renderLabels(gs);
  }

  /** Selection and error, traced above every board — see the layer's note in the markup.
   *  One path per board, kept and re-transformed rather than rebuilt: the outline is the
   *  full traced coast, and re-parsing it on every frame of a drag is not free. */
  function renderOutlines() {
    while (outlines.childElementCount > state.boards.length) outlines.lastElementChild.remove();
    while (outlines.childElementCount < state.boards.length) {
      const path = document.createElementNS(SVG_NS, 'path');
      path.setAttribute('d', BOARD.outline);
      path.setAttribute('class', 'island-pg__outline');
      // Invisible until it has a state to show, but an SVG path defaults to fill:black —
      // too load-bearing to leave to a stylesheet that might be stale.
      path.setAttribute('fill', 'none');
      outlines.appendChild(path);
    }
    state.boards.forEach((b, i) => {
      const node = outlines.children[i];
      // A blocked board is faded and dashed red to say the drop won't take; a white
      // highlight on top would drown that out, and what you are dragging is not in doubt.
      // (Careful with the wording here: Tailwind scans this file, so a bare utility name
      // in a comment mints a stray rule in app.css.)
      const blocked = !!(drag?.blocked && drag.group.includes(i));
      node.classList.toggle('is-selected', i === state.selected && !blocked);
      node.classList.toggle('has-error', !!b.error);
      const r = rot2(BOARD.center, b.rot * RAD);
      node.setAttribute('transform', `translate(${b.x - r[0]} ${b.y - r[1]}) rotate(${b.rot})`);
    });
  }

  // Initials come from player names — text, not markup, however it is spelt.
  const esc = t => String(t).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

  function renderLabels(gs) {
    while (labels.childElementCount > state.boards.length) labels.lastElementChild.remove();
    while (labels.childElementCount < state.boards.length) {
      const el = document.createElement('div');
      el.className = 'island-pg__chip';
      labels.appendChild(el);
    }
    state.boards.forEach((b, i) => {
      const el = labels.children[i];
      const [sx, sy] = project([b.x, b.y]);
      el.style.transform = `translate(${sx}px, ${sy}px) translate(-50%, -50%)`;
      el.classList.toggle('is-selected', i === state.selected);
      el.classList.toggle('has-error', !!b.error);
      // A board nobody plays says so, but it still needs a letter — which board it is decides
      // that region's terrain — so an unlettered one invites the tap that picks it. An empty
      // seat reads the same way rather than as stray punctuation.
      const letter = b.letter ? `<span class="island-pg__letter">${esc(b.letter)}</span>` : '';
      el.innerHTML = b.seated === false
        ? (letter || `<span class="island-pg__add">+</span>`) + `<span class="island-pg__who">extra</span>`
        : (b.letter || b.spiritColor)
          ? (b.spiritColor
              ? `<span class="island-pg__dot" style="background:${esc(b.spiritColor)}"></span>`
              : `<span class="island-pg__dot is-empty"></span>`) +
            letter +
            (b.initials ? `<span class="island-pg__who">${esc(b.initials)}</span>` : '')
          : `<span class="island-pg__add">+</span><span class="island-pg__who">set up</span>`;
    });
  }

  /** Coalesce redraws into a frame. A hidden tab never runs rAF, so draw straight away
   *  there — otherwise state pushed from the server while the tab is in the background
   *  would sit unrendered. */
  const invalidate = () => {
    if (document.hidden) {
      if (raf) { cancelAnimationFrame(raf); raf = 0; }
      render();
      return;
    }
    if (!raf) raf = requestAnimationFrame(render);
  };

  // ── notify the host (debounced; drags fire a lot) ──────────────────────────
  // Six decimals, not three: at 84 units to a side, three would quantise a restored
  // arrangement by enough to leave its seams a thousandth of a unit out of true.
  const snapshot = () => JSON.stringify({
    boards: state.boards.map(b => ({ rot: +b.rot.toFixed(6), x: +b.x.toFixed(6), y: +b.y.toFixed(6) })),
    bonds: state.bonds.map(b => ({ a: b.a, ae: b.ae, b: b.b, be: b.be, s: +b.s.toFixed(6) })),
  });
  /** The island as a shape, and nothing else about how it came to be one.
   *
   *  Each board's placement is expressed in some board's own frame, so sliding the island
   *  across the sea or spinning it changes nothing; the placements are then sorted, so which
   *  player sits where doesn't either; and the smallest of the results over every choice of
   *  reference board is taken, so the same island always reduces to the same string.
   *
   *  Bonds are deliberately not part of it. Unsticking a board and clicking it back into the
   *  same seam yields a physically identical island but different bond records (host and guest
   *  swap, the slide is measured from the other side), so a bond-based comparison would call
   *  that a rearrangement. */
  function arrangementOf(boards) {
    // +0 folds "-0.0" into "0.0": a coordinate a hair below zero must canonicalise the
    // same as one a hair above, or float noise makes two identical islands compare unequal.
    const coord = v => (+v.toFixed(1) + 0).toFixed(1);
    if (!boards.length) return '';
    let best = null;
    for (const ref of boards) {
      const base = invert(tfOf(ref));
      const parts = boards.map(b => {
        const p = placeOf(compose(base, tfOf(b)));
        const rot = Math.round(((p.rot % 360) + 360) % 360) % 360;   // 359.6 and -0.4 are both 0
        return `${rot}@${coord(p.x)},${coord(p.y)}`;
      }).sort();
      const s = parts.join('|');
      if (best === null || s < best) best = s;
    }
    return best;
  }

  /** The placements a stored layout describes — see applyLayout for why bonded boards are
   *  re-derived rather than read from the file. */
  function layoutPlacements(def) {
    const bondByGuest = new Map(def.bonds.map(bd => [bd.b, bd]));
    const placed = [];
    for (let i = 0; i < def.boards.length; i++) {
      const bond = bondByGuest.get(i);
      if (bond && placed[bond.a]) {
        const [P, Q] = edgeOf(placed[bond.a], bond.ae);
        placed[i] = placeOf(contactTf(P, Q, bond.be, bond.s));
      } else {
        placed[i] = { ...def.boards[i] };
      }
    }
    return placed;
  }

  /** Whether a layout describes the island currently on the sea. */
  const islandIs = (id, mine) => {
    const def = LAYOUTS[id];
    return !!def && def.boards.length === state.boards.length
        && arrangementOf(layoutPlacements(def)) === mine;
  };

  /** Which of the layouts the host offers this island actually is, or null for a shape that
   *  isn't one of them. Building Coastline by hand makes it Coastline, whichever layout
   *  happened to be seeded first — the arrangement is what a layout is.
   *
   *  The layout that was seeded wins ties, because more than one published layout can describe
   *  the same island: Fragment and Opposite Shores currently come out as the same two boards on
   *  the same seam, differing only by a turn of the whole island. Without this, picking one of
   *  them and putting a board back would silently rename it to the other. */
  function matchLayout() {
    if (!state.candidates.length) return null;
    const mine = arrangementOf(state.boards);
    if (state.seedId && state.candidates.includes(state.seedId) && islandIs(state.seedId, mine))
      return state.seedId;
    return state.candidates.find(id => islandIs(id, mine)) ?? null;
  }

  /** True when the boards still sit exactly as the seeded arrangement placed them. Covers
   *  saved shapes, which are not among the published layouts and so can't be matched by id. */
  const matchesSeed = () => state.seed !== null && state.seed === arrangementOf(state.boards);

  /** Always report: the host has to hear about becoming a layout again, not only about
   *  leaving one. */
  function notify() {
    if (!options.onChange) return;
    clearTimeout(notifyTimer);
    notifyTimer = setTimeout(() => options.onChange(snapshot(), matchLayout(), matchesSeed()), 120);
  }
  const reportSelection = () =>
    options.onSelect?.(state.selected, state.selected < 0 ? 0 : groupOf(state.selected).length);

  // ── snapping ──────────────────────────────────────────────────────────────
  /** How far apart two board centres can be and still share an edge. */
  const CONTACT_REACH = 2 * Math.max(...BOARD.corners.map(
    p => Math.hypot(p[0] - BOARD.center[0], p[1] - BOARD.center[1]))) + SNAP_DIST;

  /** The closest flush contact between the dragged island and the rest, or null.
   *  Candidates are ranked by how little the island has to move, then taken in order —
   *  the nearest contact often puts the island through a third board, and skipping to the
   *  next one is the difference between "snaps where you meant" and "won't stick at all". */
  function findSnap(movingIdx) {
    const gs = groups();
    const moving = state.boards.map((_, i) => i).filter(i => gs[i] === gs[movingIdx]);
    const still = state.boards.map((_, i) => i).filter(i => gs[i] !== gs[movingIdx]);
    if (!still.length) return null;
    const candidates = [];

    for (const m of moving) {
      const gb = state.boards[m], gTf = tfOf(gb);
      for (const ge of JOINABLE) {
        if (edgeIsBonded(m, ge)) continue;
        for (const t of still) {
          const hb = state.boards[t];
          if (Math.hypot(hb.x - gb.x, hb.y - gb.y) > CONTACT_REACH) continue;
          for (const he of JOINABLE) {
            if (edgeIsBonded(t, he)) continue;
            const [P, Q] = edgeOf(hb, he);
            for (const s of flushSlides(he, ge)) {
              const want = contactTf(P, Q, ge, s);
              const dRot = Math.abs(normDeg(want.th * DEG - gb.rot));
              if (dRot > SNAP_ANGLE) continue;
              const dPos = Math.hypot(want.tx - gTf.tx, want.ty - gTf.ty);
              if (dPos > SNAP_DIST) continue;
              candidates.push({ score: dPos + dRot * 1.2, correction: compose(want, invert(gTf)),
                                host: t, hostEdge: he, guest: m, guestEdge: ge, slide: s });
            }
          }
        }
      }
    }
    candidates.sort((a, b) => a.score - b.score);

    for (const cand of candidates.slice(0, 12)) {
      const moved = moving.map(i =>
        ({ i, b: { ...state.boards[i], ...placeOf(compose(cand.correction, tfOf(state.boards[i]))) } }));
      const clashes = moved.some(({ i, b }) => still.some(t =>
        !(t === cand.host && i === cand.guest) && boardsOverlap(b, state.boards[t])));
      if (clashes) continue;
      // Dropping into a notch can seat the island against two or three neighbours at once.
      // Bond every side that actually ends up flush, not just the one we aimed at — one bond
      // would leave the piece visibly touching a board it isn't attached to.
      const bonds = seatedContacts(moved, still);
      return { ...cand, moved, bonds: bonds.length ? bonds
        : [{ host: cand.host, hostEdge: cand.hostEdge, guest: cand.guest, guestEdge: cand.guestEdge, slide: cand.slide }] };
    }
    return null;
  }

  /** Tolerances for "this side has come to rest flush", as opposed to "could snap to". */
  const SEATED_DIST = 0.6, SEATED_ANGLE = 0.6;

  /** Every contact a candidate placement actually realises. At most one bond per side. */
  function seatedContacts(moved, still) {
    const found = [], usedHost = new Set(), usedGuest = new Set();
    for (const { i, b } of moved) {
      const gTf = tfOf(b);
      for (const ge of JOINABLE) {
        if (edgeIsBonded(i, ge) || usedGuest.has(i * 4 + ge)) continue;
        let hit = null;
        for (const t of still) {
          if (hit) break;
          const hb = state.boards[t];
          if (Math.hypot(hb.x - b.x, hb.y - b.y) > CONTACT_REACH) continue;
          for (const he of JOINABLE) {
            if (hit) break;
            if (edgeIsBonded(t, he) || usedHost.has(t * 4 + he)) continue;
            const [P, Q] = edgeOf(hb, he);
            for (const s of flushSlides(he, ge)) {
              const want = contactTf(P, Q, ge, s);
              if (Math.abs(normDeg(want.th * DEG - b.rot)) > SEATED_ANGLE) continue;
              if (Math.hypot(want.tx - gTf.tx, want.ty - gTf.ty) > SEATED_DIST) continue;
              hit = { host: t, hostEdge: he, guest: i, guestEdge: ge, slide: s };
              break;
            }
          }
        }
        if (hit) { found.push(hit); usedHost.add(hit.host * 4 + hit.hostEdge); usedGuest.add(i * 4 + ge); }
      }
    }
    return found;
  }

  /** The host side's own outline in world space, over the stretch the guest will cover.
   *  A straight chord would cut across the lobes and read as a slash through the board;
   *  following the traced points shows the actual seam that is about to close. */
  function seamPath(host, hostEdge, guestEdge, slide) {
    const T = tfOf(state.boards[host]);
    const a = corner(hostEdge), b = corner(hostEdge + 1);
    const L = edgeLen(hostEdge);
    const ux = (b[0] - a[0]) / L, uy = (b[1] - a[1]) / L;
    const lo = Math.max(0, L - slide - edgeLen(guestEdge)) - 0.5;
    const hi = Math.min(L, L - slide) + 0.5;
    const n = BOARD.outlinePoints.length;
    const out = [];
    for (let k = BOARD.edgeStart[hostEdge]; k <= BOARD.edgeStart[hostEdge + 1]; k++) {
      const p = BOARD.outlinePoints[k % n];
      const along = (p[0] - a[0]) * ux + (p[1] - a[1]) * uy;
      if (along < lo || along > hi) continue;
      const q = apply(T, p);
      out.push(`${q[0].toFixed(2)} ${q[1].toFixed(2)}`);
    }
    return out.length > 1 ? 'M' + out.join('L') : null;
  }

  function showHint(snap) {
    hintLayer.innerHTML = '';
    if (!snap) return;
    for (const bond of snap.bonds) {
      const d = seamPath(bond.host, bond.hostEdge, bond.guestEdge, bond.slide);
      if (!d) continue;
      const path = document.createElementNS(SVG_NS, 'path');
      path.setAttribute('d', d);
      path.setAttribute('class', 'island-pg__snapline');
      // Inline for the same reason as the board outlines above.
      path.setAttribute('fill', 'none');
      hintLayer.appendChild(path);
    }
  }

  function commitSnap(snap) {
    for (const { i, b } of snap.moved) state.boards[i] = b;
    for (const bond of snap.bonds)
      state.bonds.push({ a: bond.host, ae: bond.hostEdge, b: bond.guest, be: bond.guestEdge, s: bond.slide });
    hintLayer.innerHTML = '';
  }

  // ── pointer handling ──────────────────────────────────────────────────────
  const pointers = new Map();
  let drag = null;     // { index, group, startWorld, origins } | { pan: true, ... }
  let pinch = null;

  function boardIndexFromEvent(e) {
    const node = e.target.closest?.('.island-pg__board');
    return node ? +node.dataset.index : -1;
  }

  /** The pinch pair is always the first two tracked pointers. */
  const pinchPair = () => [...pointers.values()].slice(0, 2);
  const startPinch = () => {
    const [a, b] = pinchPair();
    pinch = { dist: Math.hypot(a[0] - b[0], a[1] - b[1]), scale: state.view.scale };
  };

  svg.addEventListener('pointerdown', e => {
    if (e.button !== 0 && e.pointerType === 'mouse') return;
    svg.setPointerCapture(e.pointerId);
    pointers.set(e.pointerId, [e.clientX, e.clientY]);

    if (pointers.size >= 2) {                        // pinch takes over
      // A drag the pinch interrupts never gets its pointerup bookkeeping, so settle it
      // here: put the boards back where they were and drop the snap hint — the second
      // finger says the player wanted to zoom, not to move. Fingers beyond the second
      // only re-baseline the pinch, so an accidental third can't start a drag under it.
      if (drag && !drag.pan && drag.moved) { restore(drag); hintLayer.innerHTML = ''; invalidate(); }
      host.classList.remove('is-dragging');
      drag = null;
      startPinch();
      return;
    }

    const rect = svg.getBoundingClientRect();
    const at = unproject(e.clientX - rect.left, e.clientY - rect.top);
    const idx = boardIndexFromEvent(e);
    if (idx >= 0) {
      // First tap selects (which reveals the rotate / unstick tools); tapping the board
      // that is already selected opens its setup. Without this the tools would be
      // unreachable, because the setup dialog would cover them on every tap.
      const wasSelected = state.selected === idx;
      state.selected = idx;
      const grp = groupOf(idx);
      drag = { pointerId: e.pointerId, index: idx, group: grp, from: at, moved: false, wasSelected,
               origins: grp.map(i => ({ ...state.boards[i] })) };
    } else {
      state.selected = -1;
      drag = { pointerId: e.pointerId, pan: true, from: [e.clientX, e.clientY], cx: state.view.cx, cy: state.view.cy };
    }
    // A locked island never drags its boards, so don't dress the press up as one.
    host.classList.toggle('is-dragging', !drag.pan && !state.locked);
    reportSelection();
    invalidate();
  });

  svg.addEventListener('pointermove', e => {
    if (!pointers.has(e.pointerId)) return;
    pointers.set(e.pointerId, [e.clientX, e.clientY]);

    if (pinch && pointers.size >= 2) {
      const [a, b] = pinchPair();
      const d = Math.hypot(a[0] - b[0], a[1] - b[1]);
      // Anchored at the fingers' midpoint, like the wheel path — zooming about the
      // viewport centre pulls the island out from between the fingers.
      const rect = svg.getBoundingClientRect();
      setScale(pinch.scale * d / pinch.dist,
        [(a[0] + b[0]) / 2 - rect.left, (a[1] + b[1]) / 2 - rect.top]);
      return;
    }
    if (!drag || e.pointerId !== drag.pointerId) return;

    if (drag.pan) {
      state.view.cx = drag.cx - (e.clientX - drag.from[0]) / (state.view.scale * mx());
      state.view.cy = drag.cy - (e.clientY - drag.from[1]) / state.view.scale;
      invalidate();
      return;
    }

    // A locked island can still be selected and tapped — it just doesn't move. Leaving
    // drag.moved false is what makes the release read as a tap.
    if (state.locked) return;

    const rect = svg.getBoundingClientRect();
    const at = unproject(e.clientX - rect.left, e.clientY - rect.top);
    const dx = at[0] - drag.from[0], dy = at[1] - drag.from[1];
    if (Math.abs(dx) + Math.abs(dy) > 1.5) drag.moved = true;
    drag.group.forEach((i, k) => {
      state.boards[i] = { ...state.boards[i], x: drag.origins[k].x + dx, y: drag.origins[k].y + dy };
    });
    drag.snap = findSnap(drag.index);
    drag.blocked = !drag.snap && dropOverlaps(drag.group);
    showHint(drag.snap);
    invalidate();
  });

  /** Does the dragged island now lie across a board it isn't part of? */
  function dropOverlaps(group) {
    const inGroup = new Set(group);
    return group.some(i => state.boards.some((other, t) =>
      !inGroup.has(t) && boardsOverlap(state.boards[i], other)));
  }
  const restore = d => d.group.forEach((i, k) => { state.boards[i] = { ...d.origins[k] }; });

  function endPointer(e) {
    pointers.delete(e.pointerId);
    if (pointers.size < 2) pinch = null;
    // Back down to exactly two fingers: re-baseline, or the zoom jumps to the distance
    // the pinch was first measured at.
    else if (pinch) startPinch();
    host.classList.remove('is-dragging');
    if (!drag || e.pointerId !== drag.pointerId) return;
    if (!drag.pan && drag.moved) {
      if (drag.snap) commitSnap(drag.snap);
      // Boards are physical pieces: a drop that would leave one lying across another is
      // not an arrangement anyone can set up, so put it back rather than accept it.
      else if (dropOverlaps(drag.group)) restore(drag);
      hintLayer.innerHTML = '';
      reportSelection();       // bonding changes how big the island is
      notify();
    } else if (!drag.pan && !drag.moved && drag.wasSelected) {
      options.onActivate?.(drag.index);
    }
    drag = null;
    invalidate();
  }
  svg.addEventListener('pointerup', endPointer);
  svg.addEventListener('pointercancel', endPointer);

  function setScale(next, anchor) {
    const s = Math.max(0.35, Math.min(6, next));
    if (anchor) {
      const before = unproject(anchor[0], anchor[1]);
      state.view.scale = s;
      const after = unproject(anchor[0], anchor[1]);
      state.view.cx += before[0] - after[0];
      state.view.cy += before[1] - after[1];
    } else {
      state.view.scale = s;
    }
    invalidate();
  }

  svg.addEventListener('wheel', e => {
    e.preventDefault();
    const rect = svg.getBoundingClientRect();
    setScale(state.view.scale * Math.pow(0.9992, e.deltaY), [e.clientX - rect.left, e.clientY - rect.top]);
  }, { passive: false });

  // ── public operations ─────────────────────────────────────────────────────
  /** Rotate the selected island in 60° steps about its own centre. */
  function rotate(dir) {
    if (state.locked || state.selected < 0) return;
    const grp = groupOf(state.selected);
    const before = grp.map(i => ({ ...state.boards[i] }));
    const cx = grp.reduce((a, i) => a + state.boards[i].x, 0) / grp.length;
    const cy = grp.reduce((a, i) => a + state.boards[i].y, 0) / grp.length;
    const th = dir * ROTATE_STEP * RAD;
    for (const i of grp) {
      const b = state.boards[i];
      const p = rot2([b.x - cx, b.y - cy], th);
      state.boards[i] = { ...b, x: cx + p[0], y: cy + p[1], rot: b.rot + dir * ROTATE_STEP };
    }
    // spinning an island must not park it on top of a neighbouring one
    if (dropOverlaps(grp)) { grp.forEach((i, k) => { state.boards[i] = before[k]; }); return; }
    invalidate(); notify();
  }

  /** Break every bond on the selected board and nudge it clear of its island. */
  function detach() {
    if (state.locked || state.selected < 0) return;
    const i = state.selected;
    const before = groupOf(i);
    if (!state.bonds.some(b => b.a === i || b.b === i)) return;
    state.bonds = state.bonds.filter(b => b.a !== i && b.b !== i);
    // push it away from the island it came from so the split is visible
    const rest = before.filter(k => k !== i);
    if (rest.length) {
      const cx = rest.reduce((a, k) => a + state.boards[k].x, 0) / rest.length;
      const cy = rest.reduce((a, k) => a + state.boards[k].y, 0) / rest.length;
      const b = state.boards[i];
      const d = Math.hypot(b.x - cx, b.y - cy) || 1;
      state.boards[i] = { ...b, x: b.x + (b.x - cx) / d * 26, y: b.y + (b.y - cy) / d * 26 };
    }
    reportSelection();
    invalidate(); notify();
  }

  /** Open water for a new board: clear of the boards already on the sea — and of the other
   *  boards placed in the same call, or several added at once would all land on one spot. */
  function freeSpot(n, placed) {
    const taken = state.boards.concat(placed);
    if (!taken.length) return { x: 0, y: 0 };
    const xs = taken.map(b => b.x), ys = taken.map(b => b.y);
    return { x: Math.max(...xs) + 150, y: (Math.min(...ys) + Math.max(...ys)) / 2 + (n % 2 ? 60 : -60) };
  }

  /** Centre the island and pick a scale that leaves some open water around it. Capped
   *  well below the manual zoom ceiling so a one-board island doesn't fill the frame.
   *
   *  A fit asked for before the sea has been laid out (first render, or the frame in which
   *  full screen is switched on) has nothing to measure against — it is remembered and run
   *  by the resize observer instead, so the island can never end up framed off-screen. */
  function fit() {
    if (!state.boards.length) return;
    if (!svg.clientWidth) { pendingFit = true; return; }
    pendingFit = false;
    const pts = state.boards.flatMap(b => { const T = tfOf(b); return HULL.map(p => apply(T, p)); });
    const x0 = Math.min(...pts.map(p => p[0])), x1 = Math.max(...pts.map(p => p[0]));
    const y0 = Math.min(...pts.map(p => p[1])), y1 = Math.max(...pts.map(p => p[1]));
    const pad = 30;
    const sx = svg.clientWidth / (x1 - x0 + pad * 2), sy = svg.clientHeight / (y1 - y0 + pad * 2);
    state.view.cx = (x0 + x1) / 2; state.view.cy = (y0 + y1) / 2;
    state.view.scale = Math.max(0.35, Math.min(2.6, Math.min(sx, sy)));
    invalidate();
  }

  const handle = {
    /** Replace the per-board presentation (letter, colours, error flag) and the count.
     *  Boards are matched by their stable `key`, so removing a player from the middle of
     *  the list keeps everyone else where they are — bonds are reindexed to follow, and
     *  any bond touching a departed board is dropped. New boards land in open water. */
    setBoards(list) {
      const prev = state.boards;
      const byKey = new Map(prev.map((b, i) => [b.key, { board: b, index: i }]));
      const oldToNew = new Map();
      const placedNew = [];
      const next = list.map((meta, i) => {
        const hit = byKey.get(meta.key);
        if (hit) { oldToNew.set(hit.index, i); return { ...hit.board, ...meta }; }
        const fresh = { rot: 0, ...freeSpot(placedNew.length, placedNew), ...meta };
        placedNew.push(fresh);
        return fresh;
      });
      state.bonds = state.bonds
        .filter(b => oldToNew.has(b.a) && oldToNew.has(b.b))
        .map(b => ({ ...b, a: oldToNew.get(b.a), b: oldToNew.get(b.b) }));
      state.boards = next;
      // Boards came or went, so whatever was seeded no longer describes the island. The
      // host re-applies the layout for the new count, which sets a fresh seed.
      const membershipChanged = list.length !== prev.length || oldToNew.size !== prev.length;
      if (membershipChanged) { state.seed = null; state.seedId = null; }
      // Follow the selected board through the reindex — a removal above it shifts its index,
      // and acting on the stale one would set up the wrong seat. Departed board deselects.
      const prevSelected = state.selected;
      state.selected = prevSelected >= 0 && oldToNew.has(prevSelected) ? oldToNew.get(prevSelected) : -1;
      if (state.selected !== prevSelected || (membershipChanged && state.selected >= 0)) reportSelection();
      invalidate();
    },
    /** Drop a predefined arrangement in, keeping the current board presentation. Returns
     *  whether the boards were actually moved, so the host knows whether the island has been
     *  re-framed for it.
     *
     *  Where a bond's host is already placed, the guest is re-derived from the bond instead
     *  of trusting the stored coordinates, which are rounded for file size — deriving keeps
     *  those seams exactly as flush as ones built by hand. (A guest whose host comes later
     *  in the list falls back to the stored numbers; the rounding error is far inside every
     *  snapping tolerance.) */
    applyLayout(id) {
      const def = LAYOUTS[id];
      if (!def || def.boards.length !== state.boards.length) return false;

      // Already this layout — because the player just built it, or put a board back into it.
      // Only adopt it as the seed. Re-placing would snap the island to the canonical position
      // and rotation, throwing away where the player actually left it for no gain: it is the
      // same island either way, and the form only needs to know which layout it is.
      if (arrangementOf(state.boards) === arrangementOf(layoutPlacements(def))) {
        state.seed = arrangementOf(state.boards);
        state.seedId = id;
        return false;                 // nothing moved, so nothing was re-framed either
      }

      state.boards = layoutPlacements(def).map((p, i) => ({ ...state.boards[i], ...p }));
      state.bonds = def.bonds.map(x => ({ ...x }));
      state.selected = -1;
      state.seed = arrangementOf(state.boards);
      state.seedId = id;
      reportSelection();
      fit();
      return true;    // seeding a published layout is not a custom edit — don't notify
    },
    /** Restore a previously captured arrangement (same board count). */
    setLayout(layout) {
      if (!layout?.boards || layout.boards.length !== state.boards.length) return false;
      state.boards = state.boards.map((b, i) => ({ ...b, ...layout.boards[i] }));
      state.bonds = (layout.bonds || []).map(x => ({ ...x }));
      state.selected = -1;
      // Seeded, same as a published layout: taking a board out of a saved shape and clicking
      // it back where it was should return to that shape, not leave a one-off behind.
      state.seed = arrangementOf(state.boards);
      state.seedId = null;          // a saved shape is not one of the published layouts
      reportSelection();
      fit();
      return true;
    },
    setLayoutJson(json) {
      try { return handle.setLayout(JSON.parse(json)); } catch { return false; }
    },
    /** Fix the island in place (thematic maps) or hand it back to the player. */
    setLocked(locked) {
      if (state.locked === !!locked) return;
      state.locked = !!locked;
      host.classList.toggle('is-locked', state.locked);
      invalidate();
    },
    /** Show the island from the other side of the boards — see state.mirrored. */
    setMirrored(mirrored) {
      if (state.mirrored === !!mirrored) return;
      state.mirrored = !!mirrored;
      invalidate();
    },
    /** The layouts a hand-built island may be recognised as — see state.candidates. */
    setCandidates(ids) { state.candidates = ids ?? []; },
    /** The arrangement and what it is, for a host that needs it without waiting for a change. */
    arrangement() {
      return { json: snapshot(), matchedLayoutId: matchLayout(), matchesSeed: matchesSeed() };
    },
    /** Spread every board out and drop all bonds. */
    scatter() {
      if (state.locked) return;
      const n = state.boards.length;
      const r = 70 + n * 16;
      state.boards = state.boards.map((b, i) => ({
        ...b, rot: 0,
        x: Math.cos(i / n * Math.PI * 2) * r,
        y: Math.sin(i / n * Math.PI * 2) * r * 0.7,
      }));
      state.bonds = [];
      state.selected = -1;
      reportSelection();
      fit(); notify();
    },
    rotate, detach, fit,
    zoom(mult) { setScale(state.view.scale * mult); },
    /** Current arrangement as JSON — the same payload onChange delivers. */
    snapshot,
    dispose() {
      ro?.disconnect();
      clearTimeout(notifyTimer);
      cancelAnimationFrame(raf);
      host.innerHTML = '';
      host.classList.remove('island-pg', 'is-locked', 'is-dragging');
      // Keep the devtools hook honest — a dead handle should not answer.
      delete host.islandPlayground;
    },
  };

  ro = new ResizeObserver(() => { if (pendingFit) fit(); else invalidate(); });
  ro.observe(host);
  // Reachable from the devtools console as $0.islandPlayground — handy for inspecting the
  // arrangement (`.snapshot()`) when a seam looks wrong.
  host.islandPlayground = handle;
  return handle;
}

/**
 * Blazor entry point. Returns the handle, whose methods are invoked straight from
 * .NET via IJSObjectReference (rotate, detach, applyLayout, fit, …).
 */
export function createForBlazor(host, dotnet) {
  // A dropped circuit makes every callback reject — that noise is expected and swallowed.
  // Anything else is a real error inside the .NET handler and belongs on the console.
  const disconnected = err => /circuit|disconnect|disposed/i.test(err?.message ?? '');
  const call = (name, ...args) => dotnet.invokeMethodAsync(name, ...args)
    .catch(err => { if (!disconnected(err)) console.error(`island-playground: ${name} failed`, err); });
  return create(host, {
    onChange: (json, matchedLayoutId, matchesSeed) =>
      call('OnLayoutChangedFromJs', json, matchedLayoutId, matchesSeed),
    onSelect: (index, islandSize) => call('OnSelectionChanged', index, islandSize),
    onActivate: index => call('OnBoardTapped', index),
  });
}
